import 'harness.dart';

/// Stands for the harness' marketplace root (the folder holding the install
/// scripts) when used as an argument of a [RunCommand].
const String installRoot = '{root}';

/// One step of a generated install script. The same steps render to both
/// `install.sh` and `install.ps1`.
sealed class InstallStep {
  const InstallStep(this.description);

  /// Announced before the step runs.
  final String description;
}

/// Runs `executable args`; the script stops with an error when the executable
/// is not on the PATH or exits non-zero. An argument equal to [installRoot]
/// becomes the marketplace root's absolute path.
final class RunCommand extends InstallStep {
  const RunCommand(super.description, this.executable, this.args);

  final String executable;
  final List<String> args;
}

/// Copies the files matching [pattern] in [from] (relative to the marketplace
/// root, `/`-separated) into [destination], creating it first.
final class CopyFiles extends InstallStep {
  const CopyFiles(
    super.description, {
    required this.from,
    required this.pattern,
    required this.destination,
  });

  final String from;
  final String pattern;
  final HomeDirectory destination;
}

/// Asks for the value of the environment variable [name] (a secret, so the
/// input is not echoed) and saves it for the user: `~/.profile` in the shell
/// script, the user environment in PowerShell.
///
/// Nothing is replaced: a variable that is already set, or already exported
/// from `~/.profile`, is kept. With no terminal to ask on the step is skipped
/// with a message.
final class PromptEnvVar extends InstallStep {
  PromptEnvVar(String name)
    : assert(
        RegExp(r'^[A-Za-z_][A-Za-z0-9_]*$').hasMatch(name),
        'not an environment variable name: $name',
      ),
      name = name,
      super('Set the $name environment variable');

  final String name;
}

/// One [PromptEnvVar] per environment variable the MCP [servers] reference as
/// `${NAME}`, in first-seen order. The plugin placeholders (`CLAUDE_PLUGIN_*`,
/// `PLUGIN_ROOT`, `PLUGIN_DATA`) are expanded by the client, not asked for.
List<PromptEnvVar> envVarPrompts(Map<String, dynamic>? servers) {
  var names = <String>{};
  void scan(Object? node) {
    switch (node) {
      case String():
        for (var match in _placeholder.allMatches(node)) {
          var name = match.group(1)!;
          if (!name.startsWith('CLAUDE_PLUGIN_') &&
              name != 'PLUGIN_ROOT' &&
              name != 'PLUGIN_DATA') {
            names.add(name);
          }
        }
      case Map():
        node.values.forEach(scan);
      case List():
        node.forEach(scan);
    }
  }

  scan(servers);
  return [for (final name in names) PromptEnvVar(name)];
}

final RegExp _placeholder = RegExp(r'\$\{([A-Za-z_][A-Za-z0-9_]*)\}');

/// A directory under the user's home that an environment variable can
/// relocate, e.g. `$CODEX_HOME/agents` defaulting to `~/.codex/agents`.
final class HomeDirectory {
  const HomeDirectory({
    required this.envVar,
    required this.homeFallback,
    required this.subdirectory,
  });

  final String envVar;
  final String homeFallback;
  final String subdirectory;
}

/// Writes `install.sh` and `install.ps1` for [steps] into the harness'
/// marketplace root.
void writeInstallScripts(
  HarnessContext context,
  List<InstallStep> steps, {
  required String title,
}) {
  context
    ..writeInRoot('install.sh', renderShellInstaller(steps, title: title))
    ..writeInRoot('install.ps1', renderPowerShellInstaller(steps, title: title))
    ..markExecutableInRoot('install.sh');
}

/// A POSIX `sh` script for [steps].
String renderShellInstaller(List<InstallStep> steps, {required String title}) {
  var out = StringBuffer()
    ..writeln('#!/bin/sh')
    ..writeln('# Generated by plugin_builder: installs $title.')
    ..writeln('set -eu')
    ..writeln(r'here="$(cd "$(dirname "$0")" && pwd)"')
    ..writeln('assume_yes=0')
    ..writeln(r'for arg in "$@"; do')
    ..writeln(r'  case "$arg" in --yes|-y) assume_yes=1 ;; esac')
    ..writeln('done');
  for (var i = 0; i < steps.length; i++) {
    var step = steps[i];
    out
      ..writeln()
      ..writeln(
        'echo ${_sh('[${i + 1}/${steps.length}] ${step.description}')}',
      );
    switch (step) {
      case RunCommand():
        out
          ..writeln(
            'command -v ${step.executable} >/dev/null 2>&1 || '
            '{ echo ${_sh('install: ${step.executable} not found on PATH')}'
            ' >&2; exit 1; }',
          )
          ..writeln(
            [
              step.executable,
              for (final arg in step.args)
                if (arg == installRoot) r'"$here"' else _shArg(arg),
            ].join(' '),
          );
      case PromptEnvVar():
        out.writeln(_shPrompt.replaceAll('@NAME@', step.name));
      case CopyFiles():
        var destination = step.destination;
        out
          ..writeln(
            'dest="\${${destination.envVar}:-\$HOME/${destination.homeFallback}}'
            '/${destination.subdirectory}"',
          )
          ..writeln(r'mkdir -p "$dest"')
          ..writeln('for file in "\$here/${step.from}/"${step.pattern}; do')
          ..writeln(
            r'  [ -e "$file" ] || '
            '{ echo "install: no ${step.pattern} files found" >&2; exit 1; }',
          )
          ..writeln(r'  target="$dest/$(basename "$file")"')
          ..writeln(r'  if [ -e "$target" ] && [ "$assume_yes" -ne 1 ]; then')
          ..writeln(
            "    printf '%s exists. Overwrite? [y/N] ' "
            r'"$target"',
          )
          ..writeln('    answer=n')
          ..writeln('    read -r answer || true')
          ..writeln(r'    case "$answer" in')
          ..writeln(
            '      y|Y|yes|YES) ;;'
            r' *) echo "skipped $target"; continue ;;',
          )
          ..writeln('    esac')
          ..writeln('  fi')
          ..writeln(r'  cp "$file" "$target"')
          ..writeln('done');
    }
  }
  out
    ..writeln()
    ..writeln('echo "install: done."');
  return out.toString();
}

/// A PowerShell script for [steps].
String renderPowerShellInstaller(
  List<InstallStep> steps, {
  required String title,
}) {
  var out = StringBuffer()
    ..writeln('# Generated by plugin_builder: installs $title.')
    ..writeln(r'param([switch]$Yes)')
    ..writeln(r"$ErrorActionPreference = 'Stop'")
    ..writeln(r'$Here = Split-Path -Parent $MyInvocation.MyCommand.Path');
  for (var i = 0; i < steps.length; i++) {
    var step = steps[i];
    out
      ..writeln()
      ..writeln(
        'Write-Host ${_ps('[${i + 1}/${steps.length}] ${step.description}')}',
      );
    switch (step) {
      case RunCommand():
        out
          ..writeln(
            'if (-not (Get-Command ${_ps(step.executable)} '
            '-ErrorAction SilentlyContinue)) { '
            "throw ${_ps('install: ${step.executable} not found on PATH')} }",
          )
          ..writeln(
            '& ${_ps(step.executable)} '
            '${_psArgs(step.args)}',
          )
          ..writeln(
            r'if ($LASTEXITCODE -ne 0) { '
            'throw "${step.executable} exited with \$LASTEXITCODE" }',
          );
      case PromptEnvVar():
        out.writeln(_psPrompt.replaceAll('@NAME@', step.name));
      case CopyFiles():
        var destination = step.destination;
        out
          ..writeln(
            '\$Base = if (\$env:${destination.envVar}) '
            '{ \$env:${destination.envVar} } '
            'else { Join-Path \$HOME ${_ps(destination.homeFallback)} }',
          )
          ..writeln(
            '\$Dest = Join-Path \$Base ${_ps(destination.subdirectory)}',
          )
          ..writeln(
            r'New-Item -ItemType Directory -Force -Path $Dest | Out-Null',
          )
          ..writeln(
            r'$Files = @(Get-ChildItem -Path (Join-Path $Here '
            "${_ps('${step.from}/${step.pattern}'.replaceAll('/', r'\'))}))",
          )
          ..writeln(
            r'if ($Files.Count -eq 0) { '
            "throw ${_ps('install: no ${step.pattern} files found')} }",
          )
          ..writeln(r'foreach ($File in $Files) {')
          ..writeln(r'  $Target = Join-Path $Dest $File.Name')
          ..writeln(r'  if ((Test-Path $Target) -and -not $Yes) {')
          ..writeln(
            r'    $Answer = Read-Host "$Target exists. Overwrite? [y/N]"',
          )
          ..writeln(
            r"    if ($Answer -notmatch '^[yY]') { "
            r'Write-Host "skipped $Target"; continue }',
          )
          ..writeln('  }')
          ..writeln(
            r'  Copy-Item -Path $File.FullName -Destination $Target -Force',
          )
          ..writeln('}');
    }
  }
  out
    ..writeln()
    ..writeln("Write-Host 'install: done.'");
  return out.toString();
}

const String _shPrompt = r'''
profile="$HOME/.profile"
value=
if [ -n "${@NAME@:-}" ]; then
  echo '@NAME@ is already set; keeping it'
elif grep -qs '^export @NAME@=' "$profile"; then
  echo "@NAME@ is already exported from $profile; keeping it"
elif [ ! -t 0 ]; then
  echo 'install: no terminal to ask for @NAME@ on; set it yourself' >&2
else
  printf 'Enter @NAME@: '
  stty -echo
  read -r value || true
  stty echo
  echo
  if [ -z "$value" ]; then
    echo '@NAME@ left unset: empty value'
  else
    escaped=$(printf '%s' "$value" | sed "s/'/'\\\\''/g")
    printf "export @NAME@='%s'\n" "$escaped" >> "$profile"
    echo "@NAME@ saved to $profile; restart your client to pick it up"
  fi
fi''';

const String _psPrompt = r'''
if ([Environment]::GetEnvironmentVariable('@NAME@')) {
  Write-Host '@NAME@ is already set; keeping it'
} elseif ([Console]::IsInputRedirected) {
  Write-Warning 'install: no terminal to ask for @NAME@ on; set it yourself'
} else {
  $Secret = Read-Host 'Enter @NAME@' -AsSecureString
  $Value = [System.Net.NetworkCredential]::new('', $Secret).Password
  if ($Value) {
    [Environment]::SetEnvironmentVariable('@NAME@', $Value, 'User')
    Write-Host '@NAME@ saved to your user environment; restart your client to pick it up'
  } else {
    Write-Host '@NAME@ left unset: empty value'
  }
}''';

/// [value] unquoted when it only has shell-safe characters, else quoted.
String _shArg(String value) =>
    RegExp(r'^[A-Za-z0-9_./@:=-]+$').hasMatch(value) ? value : _sh(value);

String _sh(String value) => "'${value.replaceAll("'", r"'\''")}'";

String _psArgs(List<String> args) => [
  for (final arg in args)
    if (arg == installRoot) r'$Here' else _ps(arg),
].join(' ');

String _ps(String value) => "'${value.replaceAll("'", "''")}'";
